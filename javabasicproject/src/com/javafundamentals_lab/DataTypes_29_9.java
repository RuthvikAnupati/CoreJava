/*
Task: Write a Java program to demonstrate the use of all 8 primitive data types in Java.
Requirements:
Declare and initialize one variable for each of the following:
 > byte – store your age
 > short – store the number of students in a college
 > int – store your annual salary
 > long – store a large population value
 > float – store your percentage
 > double – store your bank balance
 > char – store your grade
 > boolean – store whether you are a Java learner
Finally display all the values
*/
package com.javafundamentals_lab;

public class DataTypes_29_9 {

	public static void main(String[] args) {
		byte age = 23;
		short id = 7101;
		int pincode = 503111;
		long num1 = 4567L;
		float cgpa = 8.7F;
		double num2 = 45.677;
		char sex = 'M';
		boolean are_u_major = true;
		
		System.out.println(age);
		System.out.println(id);
		System.out.println(pincode);
		System.out.println(num1);
		System.out.println(cgpa);
		System.out.println(num2);
		System.out.println(sex);
		System.out.println(are_u_major);

	}

}
